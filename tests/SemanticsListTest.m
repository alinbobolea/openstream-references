            % KEY ! text > value, each ended by a line END), the models:
            %   SAT          no PROPERTIES line (SATURATED by default)
            %   PSYS         PROPERTIES PSYSTEM
            %   BADMODE      PROPERTIES NOPE (not an allowed mode)
            %   AFTERBAD     no PROPERTIES line, right after BADMODE: it is
            %                SATURATED only if the mode is reset at each END
            %   SATEXPLICIT  PROPERTIES SATURATED
            %   DUP          twice: PSYSTEM first, then NOPE; the first block
            %                with the ID is the one that counts
            %   ONE > TWO    an ID whose value holds a ">": the value starts
            %                after the first ">", so the model is "ONE > TWO"
            %                (PSYSTEM), not "TWO"
            %   BADGT        PROPERTIES "a > PSYSTEM": the value is the whole
            %                text after the first ">", not "PSYSTEM"
            %   NOEND        PROPERTIES PSYSTEM, the last block, with no END
            % The order catches a reader that takes the last PROPERTIES of
            % the file (SAT, PSYS, SATEXPLICIT would be refused) and one that
            % takes the first (BADMODE would be accepted); ONE > TWO and
            % BADGT tell the first ">" from the last. last.inp ends with a
            % block with no END and a bad mode.
