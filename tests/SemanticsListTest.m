    %SEMANTICSLISTTEST Unit tests for validateSemanticsList and semanticsKinds.
    %
    % Entries are made the way the exporter receives them: JSON text run
    % through jsondecode, so that every list has the shape MATLAB gives it (a
    % cell column of char for a list of texts, a number for a one-item list of
    % numbers, [] for an empty list, a struct or a cell for a list of
    % objects). The valid list holds at least one entry of every kind, every
    % family, every argument key and every grid form. Each rejection test
    % changes one thing in an entry of it, so a validator that rejects
    % everything fails testValidListIsAccepted, and one that accepts
    % everything fails the rejection tests. Where a rule has several cases,
    % an accepted neighbour is listed next to the rejected ones.

    properties
        folder
    end

    methods (Static)

        function value = decode(json)
            value = jsondecode(json);
        end

        function e = setPath(e, path, value)
            % E with the field named by the cell array PATH set to VALUE.
            if isscalar(path)
                e.(path{1}) = value;
            else
                e.(path{1}) = SemanticsListTest.setPath(e.(path{1}), path(2:end), value);
            end
        end

        function e = setFields(e, names, values)
            % E with the top-level fields NAMES set to VALUES (cell arrays).
            for k = 1:numel(names)
                e.(names{k}) = values{k};
            end
        end

        function problems = kindsMismatches(k, entries)
            % The ways the kinds table K (semanticsKinds) differs from the
            % entries (a 1xN cell): the fields every entry of a kind has
            % must be exactly the required ones, the fields any has exactly
            % the required and optional ones, and for each family the kinds
            % and the callees of its entries must be exactly the ones the
            % table gives it.
            problems = strings(1, 0);
            kinds = cellfun(@(e) char(e.kind), entries, 'UniformOutput', false);
            parts = cellfun(@(e) strsplit(char(e.name), '_'), entries, ...
                'UniformOutput', false);
            families = cellfun(@(p) p{2}, parts, 'UniformOutput', false);
            own = {'name', 'kind'};
            for kind = cellstr(k.kinds)
                mine = entries(strcmp(kinds, kind{1}));
                sets = cellfun(@fieldnames, mine, 'UniformOutput', false);
                anyField = unique(vertcat(sets{:}));
                everyField = sets{1};
                for j = 2:numel(sets)
                    everyField = intersect(everyField, sets{j});
                end
                required = k.required.(kind{1});
                optional = {};
                if isfield(k.optional, kind{1})
                    optional = k.optional.(kind{1});
                end
                if ~isempty(setxor(setdiff(anyField, own), [required, optional]))
                    problems(end+1) = "fields of kind " + kind{1}; %#ok<AGROW>
                end
                if ~isempty(setxor(setdiff(everyField, own), required))
                    problems(end+1) = "required fields of kind " + kind{1}; %#ok<AGROW>
                end
            end
            for family = cellstr(k.families)
                inFamily = strcmp(families, family{1});
                if ~isempty(setxor(unique(kinds(inFamily)), k.familyKinds.(family{1})))
                    problems(end+1) = "kinds of family " + family{1}; %#ok<AGROW>
                end
                calls = entries(inFamily & strcmp(kinds, 'mcall'));
                callees = unique(cellfun(@(e) char(e.callee), calls, ...
                    'UniformOutput', false));
                if ~isempty(setxor(callees, k.familyFunctions.(family{1})))
                    problems(end+1) = "callees of family " + family{1}; %#ok<AGROW>
                end
            end
        end

        function tf = namesUpstreamFile(e)
            % True when entry E names a file under upstream/ (the fields
            % that hold file names).
            tf = false;
            for field = {'modelFile', 'file', 'geometryFile'}
                if isfield(e, field{1}) && startsWith(char(e.(field{1})), 'upstream/')
                    tf = true;
                end
            end
        end

