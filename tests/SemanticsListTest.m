                '                         > ' name newline];
            fluid = ['FLUID      ! CoolProp fluid identifier' ...
                '                                      > WATER' newline];
            mode = @(name) ['PROPERTIES ! Assumption model for fluid properties' ...
                '> ' name newline];
            text = [ ...
                id('SAT') fluid 'END' newline newline ...
                id('PSYS') fluid mode('PSYSTEM') 'END' newline newline ...
