            testCase.verifyAccepted(local, true);
            % Negative controls: a model file that does not exist, and a
            % model that is not in its file.
            k = find(cellfun(@(e) strcmp(e.kind, 'fluid'), local), 1);
            changed = local;
            changed{k}.modelFile = 'results/absent.inp';
            testCase.verifyRejectedWith(changed, true, ...
                'results/absent.inp not found', 'model file absent');
            testCase.verifyAccepted(changed, false, 'model file absent, files not checked');
            changed = local;
            changed{k}.modelId = 'NOT_IN_THE_FILE';
            testCase.verifyRejectedWith(changed, true, ...
                'model NOT_IN_THE_FILE not found in', 'model not in its file');
        end

        function testRealManifestBrokenInOneEntryIsRejected(testCase)
            % Negative controls for testRealManifestIsAccepted: the same
            % list with one thing broken, so that acceptance of the real list
            % is not the validator accepting everything.
            entries = testCase.realEntries();
            k = find(cellfun(@(e) strcmp(e.kind, 'mcall'), entries), 1);
            changed = entries;
            changed{k}.callee = 'frobnicate';
            testCase.verifyRejectedWith(changed, false, ...
                'callee must be one of the allowlisted functions', 'unknown function');
            changed = entries;
            changed{end+1} = entries{k};
            testCase.verifyRejectedWith(changed, false, 'duplicate name(s)', 'repeated name');
            changed = entries;
            changed{k}.nargout = 5;
            testCase.verifyRejectedWith(changed, false, ...
                'nargout must be an integer from 1 to 4', 'nargout 5');
            changed = entries;
            changed{k}.extra = 1;
            testCase.verifyRejectedWith(changed, false, ...
                'unknown field(s): extra', 'unknown field');
        end

